import Foundation

/// The pasteboard types Pano stores, and the marker types it must honour. Kept in PanoCore
/// because deciding what to keep is a capture concern; the store persists whatever it is given.
public enum PasteboardUTIs {
    /// Stored, in the source app's preference order. Everything else on the pasteboard is dropped.
    public static let whitelist: Set<String> = [
        "public.file-url", "public.html", "public.png", "public.rtf",
        "public.utf8-plain-text", "public.tiff",
    ]

    /// Presence of any of these means "never record this copy" (password managers, transient UI).
    public static let markers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    static let plainText = "public.utf8-plain-text"
    static let fileURL = "public.file-url"
    static let png = "public.png"
    static let tiff = "public.tiff"
    static let rtf = "public.rtf"
    static let html = "public.html"
}
